#!/usr/bin/env python3
"""Writes src/SlackEmoji.elm from public/cacheable/compact-emoji.json.

Slack only ever names an emoji in reactions (":+1:", ":wave::skin-tone-3:"), so the backend needs
the names to turn them into the emoji at-chat stores and back. Slack's names come from the same
emoji-data set as compact-emoji.json, so its short names are Slack's names.

Run it again after compact-emoji.json changes.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
emojis = json.loads((root / "public/cacheable/compact-emoji.json").read_text())

skin_tones = {"1F3FB": "2", "1F3FC": "3", "1F3FD": "4", "1F3FE": "5", "1F3FF": "6"}

entries = []
for emoji in emojis:
    for name in emoji["short_names"]:
        entries.append((name, emoji["unified"]))
    for tone, variation in sorted((emoji.get("skin_variations") or {}).items()):
        if tone in skin_tones:
            entries.append((emoji["short_names"][0] + "::skin-tone-" + skin_tones[tone], variation["unified"]))

lines = "\n".join(
    ("    [ " if index == 0 else "    , ") + "( " + json.dumps(name) + ", " + json.dumps(unified) + " )"
    for index, (name, unified) in enumerate(entries)
)

(root / "src/SlackEmoji.elm").write_text(
    '''module SlackEmoji exposing (fromSlackName, toSlackName)

{-| Generated by scripts/generate-slack-emoji.py, don't edit by hand.

Slack names emoji in reactions instead of sending the emoji itself.

-}

import Dict exposing (Dict)
import Emoji exposing (UnicodeEmoji)
import Hex


fromSlackName : String -> Maybe UnicodeEmoji
fromSlackName name =
    Dict.get name byName |> Maybe.map unifiedToEmoji


{-| The first name Slack knows the emoji by, which is the one Slack itself uses.
-}
toSlackName : UnicodeEmoji -> Maybe String
toSlackName emoji =
    Dict.get (Emoji.toString emoji) byEmoji


byName : Dict String String
byName =
    Dict.fromList names


byEmoji : Dict String String
byEmoji =
    List.foldr
        (\\( name, unified ) dict -> Dict.insert (Emoji.toString (unifiedToEmoji unified)) name dict)
        Dict.empty
        names


unifiedToEmoji : String -> UnicodeEmoji
unifiedToEmoji unified =
    String.split "-" unified
        |> List.map
            (\\codePoint ->
                case Hex.fromString (String.toLower codePoint) of
                    Ok code ->
                        Char.fromCode code |> String.fromChar

                    Err _ ->
                        "?"
            )
        |> String.concat
        |> Emoji.fromString


names : List ( String, String )
names =
'''
    + lines
    + "\n    ]\n"
)

// Compiles src/NotificationDecoder.elm to public/notification-decoder.js, which
// public/service-worker.js imports so that it can read an encrypted message without a
// second copy of the message format written in JavaScript.
//
// Run with: npm run notification-decoder
//
// `lamdera make` appends every file in elm-pkg-js/ to whatever it compiles, so that a
// frontend build carries the app's ports with it. None of that is reachable from a service
// worker (it registers itself behind `typeof window !== 'undefined'` and its bodies only
// run when the page calls init), and it is about a third of the file, so the appended part
// is cut back off here. The cut is anchored on the line Lamdera starts it with, and this
// stops rather than guessing if that line isn't there, so a change in the compiler shows up
// as a failed build instead of a worker that silently carries the whole app.

const { execFileSync } = require("child_process");
const fs = require("fs");
const os = require("os");
const path = require("path");

const repoRoot = path.join(__dirname, "..");

const output = path.join(repoRoot, "public", "notification-decoder.js");

const marker = "\nconst pkgExports = {\n";

const compiled = path.join(
    fs.mkdtempSync(path.join(os.tmpdir(), "notification-decoder-")),
    "compiled.js");

// `lamdera` isn't on PATH, so the copy npm installed is spelled out.
const lamdera = path.join(repoRoot, "node_modules", ".bin", "lamdera");

execFileSync(
    lamdera,
    ["make", "src/NotificationDecoder.elm", "--output=" + compiled],
    { cwd: repoRoot, stdio: "inherit" });

const source = fs.readFileSync(compiled, "utf8");

const cut = source.indexOf(marker);

if (cut < 0) {
    console.error(
        "Couldn't find " + JSON.stringify(marker.trim()) + " in the compiled output, so"
            + " there's no telling where Elm stops and the elm-pkg-js Lamdera appends"
            + " starts. Check what `lamdera make` writes now and update the marker.");
    process.exit(1);
}

fs.writeFileSync(
    output,
    "// Generated by scripts/build-notification-decoder.js from src/NotificationDecoder.elm.\n"
        + "// Don't edit this by hand: run `npm run notification-decoder` instead.\n"
        + source.slice(0, cut) + "\n");

console.log(
    "Wrote " + path.relative(repoRoot, output) + " ("
        + Math.round(fs.statSync(output).size / 1024) + "kb)");
